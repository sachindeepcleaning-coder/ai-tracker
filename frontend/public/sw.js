/* AI Tracker service worker — offline after first load.
   Strategy:
   - Navigations (HTML): network-first, fall back to the cached shell when offline.
   - data.json: network-first (fresh catalog every launch), cache fallback offline.
   - Same-origin assets (hashed JS/CSS/fonts): cache-first (immutable per build).
   - Never cache cross-origin or non-GET.
   Cache name comes from ./sw-version.js (generated by regen-data.mjs from the
   data_regen_at build id), so every data rebuild busts stale caches. */
importScripts('./sw-version.js')
const CACHE = (self.SW_CACHE || 'ai-tracker-fallback')

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(['./'])))
  self.skipWaiting()
})

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))),
  )
  self.clients.claim()
})

self.addEventListener('fetch', (event) => {
  const req = event.request
  if (req.method !== 'GET') return
  const url = new URL(req.url)
  if (url.origin !== self.location.origin) return

  if (req.mode === 'navigate') {
    event.respondWith(
      fetch(req)
        .then((res) => {
          const copy = res.clone()
          caches.open(CACHE).then((c) => c.put(req, copy))
          return res
        })
        .catch(() => caches.match(req).then((hit) => hit || caches.match('./'))),
    )
    return
  }

  // Catalog payload: network-first so a new deploy is picked up on next
  // launch; the cached copy keeps the app usable offline.
  if (url.pathname.endsWith('/data.json')) {
    event.respondWith(
      fetch(req)
        .then((res) => {
          if (res.ok) {
            const copy = res.clone()
            caches.open(CACHE).then((c) => c.put(req, copy))
          }
          return res
        })
        .catch(() => caches.match(req)),
    )
    return
  }

  event.respondWith(
    caches.match(req).then(
      (hit) =>
        hit ||
        fetch(req).then((res) => {
          if (res.ok && res.type === 'basic') {
            const copy = res.clone()
            caches.open(CACHE).then((c) => c.put(req, copy))
          }
          return res
        }),
    ),
  )
})
